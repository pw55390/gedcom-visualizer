class IconManager:
    """Utility class to render SVG vector icons into Qt QIcon objects."""

    _cache = {}

    @classmethod
    def get_icon(cls, name: str, color: str = "#89b4fa", size: int = 24) -> QIcon:
        """Returns a high-DPI QIcon rendered from SVG string."""
        cache_key = (name, color, size)
        if cache_key in cls._cache:
            return cls._cache[cache_key]

        svg_template = SVG_TEMPLATES.get(name)
        if not svg_template:
            return QIcon()

        svg_data = svg_template.format(color=color).encode("utf-8")
        renderer = QSvgRenderer(svg_data)

        pixmap = QPixmap(QSize(size, size))
        pixmap.fill(Qt.GlobalColor.transparent)

        painter = QPainter(pixmap)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        renderer.render(painter)
        painter.end()

        icon = QIcon(pixmap)
        cls._cache[cache_key] = icon
        return icon
